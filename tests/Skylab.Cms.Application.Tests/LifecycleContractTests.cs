    [Fact]
    public async Task CollectionArchive_IsIdempotent_HiddenByDefault_AndVisibleOnlyToAuthorizedEditors()
    {
        var repository = new MemoryCollectionItemRepository();
        var item = CollectionItem.Create(
            CollectionKey.News,
            "reserved-story",
            NewsData("Reserved story"),
            "seed",
            DateTime.UtcNow.AddDays(-1));
        repository.Seed(item);
        var service = CreateCollectionService(repository);
        var privileged = PrincipalFactory.FromGroups("/UYELER/YK");
        var ordinaryMember = PrincipalFactory.FromGroups("/UYELER");

        var first = await service.ArchiveAsync(CollectionKey.News, item.Slug, privileged, "operator-1");
        var versionAfterFirstArchive = item.Version;
        var archivedAt = item.ArchivedAt;
        var second = await service.ArchiveAsync(CollectionKey.News, item.Slug, privileged, "operator-2");

        Assert.Null(await service.GetAsync(CollectionKey.News, item.Slug, privileged, "operator-1"));
        Assert.Empty(await service.ListArchivedAsync(CollectionKey.News, ordinaryMember));

        var archived = Assert.Single(await service.ListArchivedAsync(CollectionKey.News, privileged));
        Assert.Equal(item.Id, archived.Id);
        Assert.True(archived.IsArchived);
        Assert.Equal(archivedAt, archived.ArchivedAt);
        Assert.Equal("operator-1", archived.ArchivedBy);
        Assert.Equal(versionAfterFirstArchive, item.Version);
        Assert.Equal(first, second);
    }

    [Fact]
    public async Task CollectionRestore_IsIdempotent_AndReservedSlugCannotBeRecreated()
    {
        var repository = new MemoryCollectionItemRepository();
        var item = CollectionItem.Create(
            CollectionKey.News,
            "reserved-story",
            NewsData("Reserved story"),
            "seed",
            DateTime.UtcNow.AddDays(-1));
        item.Archive("original-archiver", DateTime.UtcNow.AddHours(-1));
        repository.Seed(item);
        var service = CreateCollectionService(repository);
        var privileged = PrincipalFactory.FromGroups("/UYELER/YK");

        var replacement = new UpsertCollectionItemRequest(NewsData("Replacement"), null);
        await Assert.ThrowsAsync<ConcurrencyConflictException>(() =>
            service.UpsertAsync(CollectionKey.News, item.Slug, replacement, privileged, "operator"));

        var first = await service.RestoreAsync(CollectionKey.News, item.Slug, privileged, "restorer-1");
        var versionAfterFirstRestore = item.Version;
        var second = await service.RestoreAsync(CollectionKey.News, item.Slug, privileged, "restorer-2");

        Assert.False(first.IsArchived);
        Assert.Null(first.ArchivedAt);
        Assert.Null(first.ArchivedBy);
        Assert.Equal(first, second);
        Assert.Equal(versionAfterFirstRestore, item.Version);
        Assert.NotNull(await service.GetAsync(CollectionKey.News, item.Slug, privileged, "restorer-1"));
        Assert.Single(repository.Items);
    }

