    [Fact]
    public async Task ContentSync_ArchivesAndRestoresIdempotently_PreservingLifecycleActorAndTime()
    {
        var repository = new MemoryContentBlockRepository();
        var draftService = new TrackingDraftService();
        var block = ContentBlock.Create(
            "skylab-site",
            "/home",
            "hero.title",
            BlockType.Text,
            JsonValue.Create("SKY LAB")!,
            0,
            "seed",
            DateTime.UtcNow.AddDays(-1));
        var otherClientBlock = ContentBlock.Create(
            "other-site",
            "/home",
            "hero.title",
            BlockType.Text,
            JsonValue.Create("Other")!,
            0,
            "seed",
            DateTime.UtcNow.AddDays(-1));
        otherClientBlock.Archive("other-operator", DateTime.UtcNow.AddHours(-4));
        repository.Seed(block, otherClientBlock);
        var service = new ContentService(repository, draftService);

        await service.SyncAsync("skylab-site", [], "deploy-1");
        var versionAfterFirstArchive = block.Version;
        var archivedAt = block.ArchivedAt;
        await service.SyncAsync("skylab-site", [], "deploy-2");

        Assert.Empty(await repository.GetBySlugAsync("skylab-site", "/home"));
        var archived = Assert.Single(await service.GetArchivedAsync("skylab-site"));
        Assert.Equal("hero.title", archived.BlockPath);
        Assert.Equal(archivedAt, archived.ArchivedAt);
        Assert.Equal("deploy-1", archived.ArchivedBy);
        Assert.Equal(versionAfterFirstArchive, block.Version);

        var manifest = new SyncManifestRequest(
            "/home",
            [new ManifestBlockItem("hero.title", BlockType.Text, JsonValue.Create("Default")!, 0)]);
        await service.SyncAsync("skylab-site", [manifest], "deploy-3");
        var versionAfterFirstRestore = block.Version;
        var repeated = await service.SyncAsync("skylab-site", [manifest], "deploy-4");

        Assert.False(block.IsArchived);
        Assert.Null(block.ArchivedAt);
        Assert.Null(block.ArchivedBy);
        Assert.Equal(versionAfterFirstRestore, block.Version);
        Assert.Equal(block.Id, Assert.Single(await repository.GetBySlugAsync("skylab-site", "/home")).Id);
        Assert.Equal(0, Assert.Single(repeated.Results).Restored);
        Assert.Equal(2, repository.Items.Count);
    }

    [Fact]
    public async Task PublishingContent_HardDeletesEphemeralRedisDraft()
    {
