        await service.UpdatePageAsync("skylab-site", request, "editor");

        Assert.Equal(("skylab-site", "editor", "/home"), Assert.Single(draftService.Deleted));
    }

    private static CollectionService CreateCollectionService(MemoryCollectionItemRepository repository)
        => new(
            repository,
            new CollectionPolicyResolver([new NewsCollectionPolicy(), new TeamsCollectionPolicy()]),
            new NoopCollectionDraftService());

    private static JsonObject NewsData(string title) => new()
    {
        ["title"] = title,
        ["body"] = $"{title} body"
    };

    private sealed class MemoryCollectionItemRepository : ICollectionItemRepository
    {
        public List<CollectionItem> Items { get; } = [];

        public void Seed(params CollectionItem[] items) => Items.AddRange(items);

        public Task<IReadOnlyList<CollectionItem>> ListAsync(
            CollectionKey key,
            bool includeArchived = false,
            CancellationToken cancellationToken = default)
        {
            IEnumerable<CollectionItem> query = Items.Where(item => item.CollectionKey == key);
            if (!includeArchived)
                query = query.Where(item => !item.IsArchived);
            return Task.FromResult<IReadOnlyList<CollectionItem>>(query.OrderBy(item => item.Slug).ToList());
        }

        public Task<(IReadOnlyList<CollectionItem> Items, int Total)> ListPagedAsync(
            CollectionKey key,
            JsonObject? filterContainment,
            int offset,
            int limit,
            CancellationToken cancellationToken = default)
        {
            var matches = Items.Where(item => item.CollectionKey == key && !item.IsArchived).ToList();
            return Task.FromResult<(IReadOnlyList<CollectionItem>, int)>((matches.Skip(offset).Take(limit).ToList(), matches.Count));
        }

        public Task<CollectionItem?> GetBySlugAsync(
            CollectionKey key,
            string slug,
            bool includeArchived = false,
            CancellationToken cancellationToken = default)
        {
            var item = Items.FirstOrDefault(item =>
                item.CollectionKey == key
                && item.Slug == slug
                && (includeArchived || !item.IsArchived));
            return Task.FromResult(item);
        }

        public Task AddAsync(CollectionItem item, CancellationToken cancellationToken = default)
        {
            Items.Add(item);
            return Task.CompletedTask;
        }

        public Task<int> SaveChangesAsync(CancellationToken cancellationToken = default) => Task.FromResult(1);
    }

    private sealed class MemoryContentBlockRepository : IContentBlockRepository
    {
        public List<ContentBlock> Items { get; } = [];

        public void Seed(params ContentBlock[] items) => Items.AddRange(items);

        public Task<IReadOnlyList<ContentBlock>> GetBySlugAsync(
            string clientId,
            string slug,
            bool includeArchived = false,
            CancellationToken cancellationToken = default)
        {
            IEnumerable<ContentBlock> query = Items.Where(item => item.ClientId == clientId && item.Slug == slug);
            if (!includeArchived)
                query = query.Where(item => !item.IsArchived);
            return Task.FromResult<IReadOnlyList<ContentBlock>>(query.OrderBy(item => item.SortOrder).ToList());
        }

        public Task<IReadOnlyList<ContentBlock>> GetByClientAsync(
            string clientId,
            bool includeArchived = false,
            CancellationToken cancellationToken = default)
        {
            IEnumerable<ContentBlock> query = Items.Where(item => item.ClientId == clientId);
            if (!includeArchived)
                query = query.Where(item => !item.IsArchived);
            return Task.FromResult<IReadOnlyList<ContentBlock>>(query.ToList());
        }

        public Task AddRangeAsync(IEnumerable<ContentBlock> blocks, CancellationToken cancellationToken = default)
        {
            Items.AddRange(blocks);
            return Task.CompletedTask;
        }

        public Task<int> SaveChangesAsync(CancellationToken cancellationToken = default) => Task.FromResult(1);
    }

    private sealed class TrackingDraftService : IDraftService
    {
        public List<(string ClientId, string UserId, string Slug)> Deleted { get; } = [];

        public Task SaveDraftAsync(string clientId, string userId, string slug, IReadOnlyList<DraftBlock> blocks, CancellationToken cancellationToken = default)
            => Task.CompletedTask;

        public Task<IReadOnlyList<DraftBlock>?> GetDraftAsync(string clientId, string userId, string slug, CancellationToken cancellationToken = default)
            => Task.FromResult<IReadOnlyList<DraftBlock>?>(null);

        public Task DeleteDraftAsync(string clientId, string userId, string slug, CancellationToken cancellationToken = default)
        {
            Deleted.Add((clientId, userId, slug));
            return Task.CompletedTask;
        }
    }

    private sealed class NoopCollectionDraftService : ICollectionDraftService
    {
        public Task SaveItemDraftAsync(CollectionKey key, string slug, string userId, JsonObject data, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task<CollectionDraft?> GetItemDraftAsync(CollectionKey key, string slug, string userId, CancellationToken cancellationToken = default) => Task.FromResult<CollectionDraft?>(null);
        public Task DeleteItemDraftAsync(CollectionKey key, string slug, string userId, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task SaveVirtualDraftAsync(CollectionKey key, string slug, string userId, JsonObject data, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task<CollectionDraft?> GetVirtualDraftAsync(CollectionKey key, string slug, string userId, CancellationToken cancellationToken = default) => Task.FromResult<CollectionDraft?>(null);
        public Task DeleteVirtualDraftAsync(CollectionKey key, string slug, string userId, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task SaveNewDraftAsync(CollectionKey key, string userId, string? slug, JsonObject data, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task<CollectionDraft?> GetNewDraftAsync(CollectionKey key, string userId, CancellationToken cancellationToken = default) => Task.FromResult<CollectionDraft?>(null);
        public Task DeleteNewDraftAsync(CollectionKey key, string userId, CancellationToken cancellationToken = default) => Task.CompletedTask;
    }
